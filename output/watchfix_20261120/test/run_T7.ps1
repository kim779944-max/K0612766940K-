# T7 문법 검사 (지시서 명령 그대로 + 파서 오류 수 + BOM)
. (Join-Path $PSScriptRoot '_lib.ps1')
'== T7 ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
$o = powershell -NoProfile -Command "[void][scriptblock]::Create((Get-Content -Raw '$Script')); 'scriptblock OK'" 2>&1 | Out-String
'  ' + $o.Trim()
$e = $null; [void][System.Management.Automation.Language.Parser]::ParseFile($Script, [ref]$null, [ref]$e)
$bytes = [IO.File]::ReadAllBytes($Script)
Check '[scriptblock]::Create 오류 0' ($o -match 'scriptblock OK')
Check "파서 오류 $($e.Count)개" ($e.Count -eq 0)
Check 'UTF-8 BOM 있음' ($bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF)
