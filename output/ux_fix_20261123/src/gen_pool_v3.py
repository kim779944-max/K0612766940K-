import io, json, os, re, sys

NAV = sys.argv[1]
src = io.open(os.path.join(NAV, "js", "data.pool.js"), encoding="utf-8").read().replace("\r\n", "\n")
# 원래 층별·결별 사진
by = {}
cur = None
for line in src.split("\n"):
    m = re.match(r"^(\d+): \{", line)
    if m: cur = int(m.group(1)); continue
    m = re.search(r"t:'(\w+)'.*img:'(img/opts/[^']+)'", line)
    if m and cur: by.setdefault((cur, m.group(1)), []).append(m.group(2))
used = set()


def img(layers, t):
    for L in layers:
        for x in by.get((L, t), []):
            if x not in used: used.add(x); return x
    for (L, tt), arr in sorted(by.items()):  # 같은 결 아무 층
        if tt == t:
            for x in arr:
                if x not in used: used.add(x); return x
    raise SystemExit(f"no img for {layers} {t}")


def o(l, t, t2, p, s, layers):
    return {"l": l, "t": t, "t2": t2, "p": p, "s": s, "img": img(layers, t)}


